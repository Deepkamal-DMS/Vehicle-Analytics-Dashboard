/*
 * Regenerates supabase/migrations/20260922120000_import_maker_month.sql
 * from tools/class-columns.js. Run this - never hand-edit that SQL
 * file - if the class list ever changes, so the 75-column INSERT
 * and jsonb_to_recordset() lists in it can't drift from the one
 * canonical source every import path reads.
 *
 * After regenerating, re-run the SQL against Supabase (see that
 * migration file's own header) and re-test with the queries this
 * function's tests were built from before trusting it again.
 *
 * Usage (from the repo root): node tools/generate-import-migration.js
 */

const fs = require("fs");
const path = require("path");
const { CLASS_COLUMNS, MONTHS } = require(
    path.resolve("tools", "class-columns.js")
);

const quoted = name => '"' + name.replace(/"/g, '""') + '"';

const recordsetCols = ['"Maker" text']
    .concat(CLASS_COLUMNS.map(name => `${quoted(name)} integer`))
    .concat(['"Total" integer']);

const insertCols = ['"year"', '"Maker"']
    .concat(CLASS_COLUMNS.map(quoted))
    .concat(['"Total"']);

/*
 * Every class column is coalesced to 0: the live table declares all
 * 75 of them NOT NULL DEFAULT 0, and a row whose JSON object simply
 * omits a class (jsonb_to_recordset then leaves it NULL) should mean
 * "zero of that class", not a rejected insert. validate.js always
 * sends all 75 keys, so this never fires from the Edge Function in
 * practice - it is here so a malformed payload fails on its actual
 * problem, not on an unrelated NOT NULL violation for a column that
 * was simply never involved.  Maker and Total are NOT coalesced: an
 * absent maker name or total is a genuinely broken row, and should
 * fail loudly rather than be papered over.
 */
const selectCols = ['$2', 't."Maker"']
    .concat(CLASS_COLUMNS.map(name => `coalesce(t.${quoted(name)}, 0)`))
    .concat(['t."Total"']);

const sumExpr = CLASS_COLUMNS.map(name => `coalesce(t.${quoted(name)}, 0)`)
    .join(" + ");

const monthList = MONTHS.map(m => `'${m}'`).join(", ");

const RECORDSET_ARGS = recordsetCols.join(",\n            ");

const sql = `-- Generated by a one-off script from tools/class-columns.js - the
-- 75 vehicle-class columns below are copy-pasted from nowhere else,
-- they are generated from the exact same array tools/build-month-tables.js
-- uses for the offline import path, so the two paths cannot drift apart
-- on column names or order.
--
-- import_maker_month() is the ONLY way a single month+year of Maker x
-- Vehicle Class data can be replaced. It is deliberately narrow:
--
--   - p_month must be one of the 12 literal month codes below. The
--     table name is built with format(%I) only after that check, so
--     no caller-supplied text ever reaches a table/column identifier
--     unvalidated.
--   - p_year must be within the same 2000-2100 range the table's own
--     CHECK constraint enforces, checked here too so a bad year fails
--     before anything is touched rather than mid-statement.
--   - The whole call is one transaction: delete-then-insert either
--     both happen or neither does. A month is never left half-loaded.
--   - Only that one (month, year) pair is touched - DELETE is scoped
--     to "year" = p_year, matching the documented safe recovery path
--     in tools/schema.sql ("Deleting one year is only useful if you
--     are importing a single-year file"). Every other year, and every
--     other month table, is untouched.
--   - Granted to service_role only. anon and authenticated - the
--     roles the dashboard's publishable key can ever authenticate
--     as - are explicitly revoked, so the publishable key already
--     shipped in script.js cannot call this even by hand-crafting a
--     REST request to /rest/v1/rpc/import_maker_month.

CREATE OR REPLACE FUNCTION public.import_maker_month(
    p_month text,
    p_year integer,
    p_rows jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_table      text;
    v_deleted    integer;
    v_inserted   integer;
    v_units      bigint;
    v_mismatches jsonb;
BEGIN
    IF p_month NOT IN (${monthList}) THEN
        RAISE EXCEPTION 'import_maker_month: unknown month %', p_month
            USING ERRCODE = 'invalid_parameter_value';
    END IF;

    IF p_year IS NULL OR p_year < 2000 OR p_year > 2100 THEN
        RAISE EXCEPTION 'import_maker_month: year % out of range', p_year
            USING ERRCODE = 'invalid_parameter_value';
    END IF;

    IF p_rows IS NULL OR jsonb_typeof(p_rows) <> 'array'
            OR jsonb_array_length(p_rows) = 0 THEN
        RAISE EXCEPTION 'import_maker_month: rows must be a non-empty array'
            USING ERRCODE = 'invalid_parameter_value';
    END IF;

    v_table := format('Maker_Class_Wise_%s', p_month);

    EXECUTE format('DELETE FROM %I WHERE "year" = $1', v_table)
        USING p_year;
    GET DIAGNOSTICS v_deleted = ROW_COUNT;

    EXECUTE format(
        'INSERT INTO %I (${insertCols.join(", ")})
         SELECT ${selectCols.join(", ")}
         FROM jsonb_to_recordset($1) AS t(
            ${RECORDSET_ARGS}
         )',
        v_table
    ) USING p_rows, p_year;
    GET DIAGNOSTICS v_inserted = ROW_COUNT;

    EXECUTE format(
        'SELECT coalesce(sum("Total"), 0) FROM %I WHERE "year" = $1',
        v_table
    ) INTO v_units USING p_year;

    /*
     * A mismatch here is reported, not raised - the CLI path
     * (build-month-tables.js) has always loaded a row even when its
     * class columns do not sum to its own Total, flagging it as a
     * warning for a human to see rather than refusing the file. This
     * keeps that same behaviour: the caller gets the list back and
     * decides, the transaction still commits.
     */
    EXECUTE format(
        'SELECT coalesce(jsonb_agg(jsonb_build_object(
                ''maker'', "Maker", ''total'', "Total", ''summed'', summed
            )), ''[]''::jsonb)
         FROM (
             SELECT t."Maker", t."Total", (${sumExpr}) AS summed
             FROM %I AS t WHERE t."year" = $1
         ) s
         WHERE s."Total" IS DISTINCT FROM s.summed',
        v_table
    ) INTO v_mismatches USING p_year;

    RETURN jsonb_build_object(
        'table', v_table,
        'year', p_year,
        'deleted', v_deleted,
        'inserted', v_inserted,
        'units', v_units,
        'mismatches', v_mismatches
    );
END;
$$;

REVOKE ALL ON FUNCTION public.import_maker_month(text, integer, jsonb)
    FROM PUBLIC;

/*
 * PUBLIC alone is not enough on Supabase: new functions in the
 * public schema get EXECUTE granted directly to anon and
 * authenticated by ALTER DEFAULT PRIVILEGES set up when the project
 * was provisioned - a separate, specific grant, not something
 * inherited through PUBLIC, so revoking from PUBLIC does not touch
 * it. Both are revoked explicitly here for exactly that reason -
 * confirmed by testing directly against the live project, where the
 * PUBLIC-only revoke below left anon able to call this function.
 */
REVOKE ALL ON FUNCTION public.import_maker_month(text, integer, jsonb)
    FROM anon, authenticated;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
        GRANT EXECUTE ON FUNCTION public.import_maker_month(text, integer, jsonb)
            TO service_role;
    END IF;
END;
$$;
`;

fs.writeFileSync(
    path.resolve("supabase", "migrations", "20260922120000_import_maker_month.sql"),
    sql,
    "utf8"
);
console.log("written");
