/*
 * Copies the six year-grain scope tables out of the live Supabase
 * project so the local database is a full stand-in, not just the
 * monthly half.
 *
 * Read-only: it uses the same publishable anon key script.js ships
 * with, which grants SELECT and nothing else.
 *
 * Writes  local/data/<table>.csv
 *         local/init/05-scope-tables.sql
 *
 * Column order and types come from the rows themselves - "year" is
 * a smallint, "Maker" is text, everything else is a count. These
 * keep production's NOT NULL DEFAULT 0, unlike the new monthly
 * tables, so the two schemas can be measured against each other.
 *
 * Usage:  node tools/fetch-scope-tables.js
 */

const fs = require("fs");
const path = require("path");


const REPO_ROOT = path.resolve(__dirname, "..");

const CSV_OUT_DIR = path.join(REPO_ROOT, "local", "data");
const SQL_OUT = path.join(REPO_ROOT, "local", "init", "05-scope-tables.sql");

const API_URL = "https://ytgoonducepylslknkag.supabase.co/rest/v1";

const API_KEY = "sb_publishable_9IVGzYTxQDj2UoLOaBtkFw_7H5ILVGY";

const HEADERS = {
    apikey: API_KEY,
    Authorization: `Bearer ${API_KEY}`
};

const TABLES = [
    "MAKER_WISE",
    "Gujarat_Class_Wise",
    "Maker_Class_Wise_GJ01",
    "Maker_Class_Wise_GJ13",
    "Maker_Class_Wise_GJ27",
    "Maker_Class_Wise_GJ38"
];

const PAGE = 1000;


function quote(name) {
    return `"${name.replace(/"/g, '""')}"`;
}


function csvCell(value) {

    if (value === null || value === undefined) {
        return "";
    }

    const text = String(value);

    return /[",\r\n]/.test(text)
        ? `"${text.replace(/"/g, '""')}"`
        : text;
}


async function fetchAll(table) {

    const rows = [];

    for (let from = 0; ; from += PAGE) {

        const response = await fetch(
            `${API_URL}/${encodeURIComponent(table)}?select=*`,
            {
                headers: {
                    ...HEADERS,
                    Range: `${from}-${from + PAGE - 1}`
                }
            }
        );

        if (!response.ok) {
            throw new Error(
                `${table}: ${response.status} ${await response.text()}`
            );
        }

        const page = await response.json();

        rows.push(...page);

        if (page.length < PAGE) {
            return rows;
        }
    }
}


function schemaFor(table, columns) {

    const width = Math.max(...columns.map(name => quote(name).length), 12);

    const body = columns.map(name => {

        const padded = quote(name).padEnd(width);

        if (name === "year") {
            return `    ${padded} smallint NOT NULL`;
        }

        if (name === "Maker") {
            return `    ${padded} text     NOT NULL`;
        }

        return `    ${padded} integer  NOT NULL DEFAULT 0`;
    });

    body.push('    PRIMARY KEY ("year", "Maker")');

    const name = quote(table);

    return [
        `CREATE TABLE ${name} (`,
        body.join(",\n"),
        ");",
        "",
        `ALTER TABLE ${name} ENABLE ROW LEVEL SECURITY;`,
        "",
        `GRANT SELECT ON TABLE ${name} TO anon, authenticated;`,
        "",
        `CREATE POLICY "anon read ${table}" ON ${name}`,
        "    FOR SELECT TO anon, authenticated USING (true);",
        ""
    ].join("\n");
}


async function main() {

    fs.mkdirSync(CSV_OUT_DIR, { recursive: true });

    const sql = [
        "-- Generated by tools/fetch-scope-tables.js - do not edit by hand.",
        "--",
        "-- The six year-grain scope tables, copied from the live",
        "-- Supabase project. NOT NULL DEFAULT 0 is production's shape,",
        "-- kept verbatim so it can be measured against the nullable",
        "-- monthly tables.",
        ""
    ];

    for (const table of TABLES) {

        const rows = await fetchAll(table);

        if (rows.length === 0) {
            throw new Error(`${table}: no rows returned`);
        }

        const columns = Object.keys(rows[0]);

        const lines = [columns.map(csvCell).join(",")];

        for (const row of rows) {
            lines.push(columns.map(name => csvCell(row[name])).join(","));
        }

        fs.writeFileSync(
            path.join(CSV_OUT_DIR, `${table}.csv`),
            lines.join("\n") + "\n",
            "utf8"
        );

        sql.push(schemaFor(table, columns));

        const units = rows.reduce(
            (sum, row) => sum + (Number(row.Total) || 0),
            0
        );

        console.log(
            table.padEnd(24) +
            String(rows.length).padStart(6) + " rows  " +
            String(columns.length).padStart(3) + " cols  " +
            units.toLocaleString("en-IN").padStart(12) + " units"
        );
    }

    fs.writeFileSync(SQL_OUT, sql.join("\n"), "utf8");

    console.log(`\nCSVs -> ${CSV_OUT_DIR}`);
    console.log(`SQL  -> ${SQL_OUT}`);
}


main().catch(error => {
    console.error(error.message);
    process.exit(1);
});
