/*
 * Builds three views so the monthly trend can be read in two small
 * requests instead of paging every maker-row in the database.
 *
 * The dashboard was fetching 37,074 rows over 44 paged requests to
 * fill a 4 x 12 grid - roughly 1,159 rows per cell displayed. All
 * three of these aggregate or narrow server-side.
 *
 *   monthly_by_maker  the twelve month tables as one relation, with
 *                     a month column. Filtered by Maker it returns
 *                     32 rows, which is the trend's VOL series.
 *
 *   monthly_totals    per month and year, every class column summed
 *                     across all makers. 32 rows. Gives IND, and
 *                     also VOL whenever no single maker is chosen.
 *
 *   monthly_makers    the distinct maker list, for the trend's own
 *                     Maker select.
 *
 * security_invoker keeps the views subject to the base tables' row
 * level security rather than bypassing it.
 *
 * Usage:
 *     export SUPABASE_ACCESS_TOKEN=sbp_...
 *     node tools/create-monthly-views.js [--dry-run]
 */

const fs = require("fs");
const path = require("path");


const PROJECT_REF = "ytgoonducepylslknkag";
const API = `https://api.supabase.com/v1/projects/${PROJECT_REF}/database/query`;

const SQL_OUT = path.resolve(__dirname, "monthly-views.sql");

const MONTHS = [
    "Jan", "Feb", "Mar", "Apr", "May", "Jun",
    "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"
];

const SOURCE_PREFIX = "Maker_Class_Wise_";

const token = process.env.SUPABASE_ACCESS_TOKEN;
const dryRun = process.argv.includes("--dry-run");


function quoteIdent(name) {
    return '"' + name.replace(/"/g, '""') + '"';
}


async function runSql(sql, label) {

    const response = await fetch(API, {
        method: "POST",
        headers: {
            Authorization: `Bearer ${token}`,
            "Content-Type": "application/json"
        },
        body: JSON.stringify({ query: sql })
    });

    const body = await response.text();

    if (!response.ok) {

        let detail = body.slice(0, 400);

        try {
            const parsed = JSON.parse(body);
            detail = parsed.message || parsed.error || detail;
        } catch (ignored) {
            /* non-JSON error body */
        }

        throw new Error(`${label}: HTTP ${response.status} - ${detail}`);
    }

    try {
        return JSON.parse(body);
    } catch (ignored) {
        return [];
    }
}


async function classColumnsOf(table) {

    const rows = await runSql(
        `SELECT column_name FROM information_schema.columns ` +
        `WHERE table_schema='public' AND table_name='${table}' ` +
        `ORDER BY ordinal_position;`,
        `columns of ${table}`
    );

    return rows
        .map(row => row.column_name)
        .filter(name => !["year", "Maker", "Total"].includes(name));
}


function buildSql(classColumns) {

    const classList = classColumns.map(quoteIdent).join(", ");

    const branches = MONTHS.map((month, index) =>
        `    SELECT ${index + 1} AS month, "year", "Maker", ` +
        `${classList}, "Total"\n` +
        `    FROM ${quoteIdent(SOURCE_PREFIX + month)}`
    ).join("\n    UNION ALL\n");

    const sums = classColumns
        .map(c => `    sum(${quoteIdent(c)})::bigint AS ${quoteIdent(c)}`)
        .join(",\n");

    return [
        `-- Generated by tools/create-monthly-views.js - do not edit by hand.`,
        `--`,
        `-- Aggregates for the monthly trend. Without these the browser`,
        `-- pages all 37,074 maker-rows to fill a 4 x 12 grid.`,
        ``,
        `DROP VIEW IF EXISTS "monthly_makers";`,
        `DROP VIEW IF EXISTS "monthly_totals";`,
        `DROP VIEW IF EXISTS "monthly_by_maker";`,
        ``,
        `-- The twelve month tables as one relation.`,
        `CREATE VIEW "monthly_by_maker" WITH (security_invoker = on) AS`,
        branches + `;`,
        ``,
        `-- Every class summed across makers, per month and year.`,
        `CREATE VIEW "monthly_totals" WITH (security_invoker = on) AS`,
        `SELECT`,
        `    month,`,
        `    "year",`,
        sums + `,`,
        `    sum("Total")::bigint AS "Total"`,
        `FROM "monthly_by_maker"`,
        `GROUP BY month, "year";`,
        ``,
        `-- Distinct makers, for the trend's own Maker select.`,
        `CREATE VIEW "monthly_makers" WITH (security_invoker = on) AS`,
        `SELECT DISTINCT "Maker" FROM "monthly_by_maker";`,
        ``,
        `GRANT SELECT ON "monthly_by_maker" TO anon, authenticated;`,
        `GRANT SELECT ON "monthly_totals"   TO anon, authenticated;`,
        `GRANT SELECT ON "monthly_makers"   TO anon, authenticated;`,
        ``,
        `NOTIFY pgrst, 'reload schema';`,
        ``
    ].join("\n");
}


async function main() {

    if (!token && !dryRun) {
        console.error("SUPABASE_ACCESS_TOKEN is not set.");
        process.exitCode = 1;
        return;
    }

    const classColumns = await classColumnsOf(`${SOURCE_PREFIX}Jan`);

    console.log(`${classColumns.length} class columns from ${SOURCE_PREFIX}Jan`);

    const sql = buildSql(classColumns);

    fs.writeFileSync(SQL_OUT, sql, "utf8");
    console.log(`sql -> ${SQL_OUT} (${Math.round(sql.length / 1024)} KB)`);

    if (dryRun) {
        console.log("dry run - nothing was sent");
        return;
    }

    await runSql(sql, "create views");
    console.log("views created");

    /* ---- verify against the tables they replace ---- */

    const [shape] = await runSql(
        `SELECT
           (SELECT count(*) FROM "monthly_totals")::int      AS total_rows,
           (SELECT count(*) FROM "monthly_makers")::int      AS maker_rows,
           (SELECT count(*) FROM "monthly_by_maker")::int    AS union_rows,
           (SELECT sum("Total") FROM "monthly_totals")::bigint  AS view_units,
           (SELECT sum("Total") FROM "monthly_by_maker")::bigint AS union_units;`,
        "shape"
    );

    console.log("");
    console.log(`monthly_by_maker  ${shape.union_rows} rows   ` +
        `${Number(shape.union_units).toLocaleString("en-IN")} units`);
    console.log(`monthly_totals    ${shape.total_rows} rows   ` +
        `${Number(shape.view_units).toLocaleString("en-IN")} units`);
    console.log(`monthly_makers    ${shape.maker_rows} rows`);

    const problems = [];

    if (Number(shape.union_rows) !== 37074) {
        problems.push(`union has ${shape.union_rows} rows, expected 37074`);
    }

    if (Number(shape.view_units) !== 76970620) {
        problems.push(`totals sum to ${shape.view_units}, expected 76970620`);
    }

    if (Number(shape.view_units) !== Number(shape.union_units)) {
        problems.push("aggregate does not match the union it is built from");
    }

    /*
     * The aggregate must agree with the source tables month by month,
     * not just in total - a mis-ordered UNION branch would keep the
     * grand total intact while moving figures between months.
     */
    const perMonth = await runSql(
        MONTHS.map((month, index) =>
            `SELECT ${index + 1} AS m, ` +
            `(SELECT coalesce(sum("Total"),0) FROM ` +
            `${quoteIdent(SOURCE_PREFIX + month)})::bigint AS src, ` +
            `(SELECT coalesce(sum("Total"),0) FROM "monthly_totals" ` +
            `WHERE month = ${index + 1})::bigint AS agg`
        ).join(" UNION ALL ") + " ORDER BY 1;",
        "per month"
    );

    for (const row of perMonth) {
        if (Number(row.src) !== Number(row.agg)) {
            problems.push(
                `month ${row.m}: view ${row.agg} but table ${row.src}`
            );
        }
    }

    console.log("");

    if (problems.length > 0) {
        console.error("verification failed:");
        for (const problem of problems) {
            console.error(`  ${problem}`);
        }
        process.exitCode = 1;
        return;
    }

    console.log("every month matches its source table");
}


main().catch(error => {
    console.error("");
    console.error(error.message);
    process.exitCode = 1;
});
