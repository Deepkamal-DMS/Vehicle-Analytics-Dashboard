/*
 * Generates the CREATE TABLE SQL for the three-table rebuild:
 * All India, Gujarat RTO-wise (37 RTOs), Maharashtra RTO-wise (58
 * RTOs) - replacing the ~50 tables/views dropped in
 * supabase/migrations/20260924130000_drop_all_scope_tables.sql.
 *
 * One table per source, month grain from the start (year, month,
 * Maker, [rto_code, rto_name where the source is RTO-wise], every
 * class in tools/class-columns.js, Total, uploaded_at) - not one
 * table per RTO the way the old schema was, since the real data has
 * 37 + 58 RTOs, not 4. Year and per-scope totals become SQL views on
 * top of these later, not separate physical tables.
 *
 * Usage:  node tools/build-new-schema.js > supabase/migrations/<timestamp>_create_new_schema.sql
 */

const { CLASS_COLUMNS, ENTITY_COLUMN, TOTAL_COLUMN, MONTHS } = require("./class-columns.js");

function quote(name) {
    return `"${name.replace(/"/g, '""')}"`;
}

const MONTH_CHECK = MONTHS.map(m => `'${m}'`).join(", ");

/*
 * hasRto: adds rto_code/rto_name and folds them into the primary
 * key. Every column list is built from the same CLASS_COLUMNS array
 * build-month-tables.js and the online import path already use, so
 * a class can't quietly exist in one place and not another.
 */
const TABLES = [
    { name: "All_India_Class_Wise", hasRto: false },
    { name: "Gujarat_RTO_Class_Wise", hasRto: true },
    { name: "Maharashtra_RTO_Class_Wise", hasRto: true }
];

function columnLines(hasRto) {

    const lines = [
        `    ${quote("year")} smallint NOT NULL CHECK (${quote("year")} BETWEEN 2000 AND 2100)`,
        `    , ${quote("month")} text NOT NULL CHECK (${quote("month")} IN (${MONTH_CHECK}))`
    ];

    if (hasRto) {
        lines.push(`    , ${quote("rto_code")} text NOT NULL`);
        lines.push(`    , ${quote("rto_name")} text NOT NULL`);
    }

    lines.push(`    , ${quote(ENTITY_COLUMN)} text NOT NULL`);

    CLASS_COLUMNS.forEach(name => {
        lines.push(`    , ${quote(name)} integer NOT NULL DEFAULT 0`);
    });

    lines.push(`    , ${quote(TOTAL_COLUMN)} integer NOT NULL DEFAULT 0`);

    /*
     * When this row was last loaded, not when Vahan published the
     * data (that's "year"/"month") - set once at insert, refreshed
     * naturally on whatever future replace-this-month RPC re-inserts
     * it, the same way import_maker_month()'s delete-then-insert
     * would.
     */
    lines.push(`    , ${quote("uploaded_at")} timestamptz NOT NULL DEFAULT now()`);

    return lines;
}

function primaryKey(hasRto) {

    const cols = ["year", "month"];

    if (hasRto) {
        cols.push("rto_code");
    }

    cols.push(ENTITY_COLUMN);

    return cols.map(quote).join(", ");
}

function buildTable({ name, hasRto }) {

    const table = quote(name);
    const policy = quote(`anon read ${name}`);

    return [
        `CREATE TABLE ${table} (`,
        columnLines(hasRto).join("\n"),
        `    , PRIMARY KEY (${primaryKey(hasRto)})`,
        `);`,
        ``,
        `ALTER TABLE ${table} ENABLE ROW LEVEL SECURITY;`,
        ``,
        `GRANT SELECT ON TABLE ${table} TO anon, authenticated;`,
        ``,
        `DROP POLICY IF EXISTS ${policy} ON ${table};`,
        ``,
        `CREATE POLICY ${policy} ON ${table}`,
        `    FOR SELECT TO anon, authenticated USING (true);`,
        ``
    ].join("\n");
}

function buildSql() {

    return [
        `-- Generated by tools/build-new-schema.js - do not edit by hand.`,
        `--`,
        `-- Three tables replacing the ~50 dropped in`,
        `-- 20260924130000_drop_all_scope_tables.sql: one table per`,
        `-- source (All India, Gujarat RTO-wise, Maharashtra RTO-wise),`,
        `-- an rto_code/rto_name row instead of a table per RTO, and`,
        `-- month grain from the start rather than year-grain tables`,
        `-- with a separate month-grain set behind them.`,
        `--`,
        `-- ${CLASS_COLUMNS.length} vehicle-class columns per table, from`,
        `-- tools/class-columns.js - the same array the online import`,
        `-- path (supabase/functions/import-workbook) and the offline`,
        `-- one (build-month-tables.js) both read, so this schema and`,
        `-- whatever writes to it next cannot drift on column names.`,
        `--`,
        `-- The SELECT-only policy matches every table this project has`,
        `-- ever had: the publishable key in script.js stays read-only.`,
        `-- Nothing in this migration grants write access to anything -`,
        `-- that is a separate RPC, written once real loading starts.`,
        ``,
        `GRANT USAGE ON SCHEMA public TO anon, authenticated;`,
        ``,
        TABLES.map(buildTable).join("\n"),
        `NOTIFY pgrst, 'reload schema';`,
        ``
    ].join("\n");
}

if (require.main === module) {
    process.stdout.write(buildSql());
}

module.exports = { buildSql, TABLES };
